/**
 * Helper to generate a clean list of patched fixtures with automatic orderInGroup & stageX/Y coordinates
 */
export function buildPatchedRigFromSpecs(
  specs: Array<{
    count: number;
    profileId: string;
    groupId: GroupId;
    namePrefix: string;
    universe: number;
    startAddress: number;
  }>
): PatchedFixture[] {
  const result: PatchedFixture[] = [];
  const rowYByGroup: Record<GroupId, number> = {
    beams: 0.16,
    spots: 0.3,
    washes: 0.46,
    blinders: 0.62,
    strobes: 0.76,
    bars: 0.9,
  };

  const defaultZoneByGroup: Record<GroupId, LocationZoneId> = {
    beams: 'back_truss',
    spots: 'back_truss',
    washes: 'mid_truss',
    blinders: 'front_truss',
    strobes: 'front_truss',
    bars: 'floor_totems',
  };

  for (const spec of specs) {
    const profile = FIXTURE_PROFILES.find((p) => p.id === spec.profileId) || FIXTURE_PROFILES[0];
    let currentAddr = spec.startAddress;
    let currentUni = spec.universe;

    for (let i = 0; i < spec.count; i++) {
      if (currentAddr + profile.channelCount - 1 > 512) {
        currentUni++;
        currentAddr = 1;
      }
      result.push({
        id: `${spec.groupId}_${spec.profileId}_${i + 1}_${Math.random().toString(36).slice(2, 6)}`,
        name: `${spec.namePrefix} #${i + 1}`,
        profileId: spec.profileId,
        groupId: spec.groupId,
        locationZone: defaultZoneByGroup[spec.groupId],
        universe: currentUni,
        address: currentAddr,
        orderInGroup: i,
        stageX: spec.count === 1 ? 0 : -1 + (2 * i) / (spec.count - 1),
        stageY: rowYByGroup[spec.groupId],
      });
      currentAddr += profile.channelCount;
    }
  }

  return normalizeGroupOrders(result);
}

/**
 * Recalculates orderInGroup (0..N-1) and normalized stageX (-1..+1) for every group
 * so symmetric effects, fans, and wings ALWAYS adapt automatically to the current fixture count.
 */
export function normalizeGroupOrders(fixtures: PatchedFixture[]): PatchedFixture[] {
  const groups: GroupId[] = ['beams', 'washes', 'spots', 'blinders', 'strobes', 'bars'];
  const rowYByGroup: Record<GroupId, number> = {
    beams: 0.16,
    spots: 0.3,
    washes: 0.46,
    blinders: 0.62,
    strobes: 0.76,
    bars: 0.9,
  };

  const updated = [...fixtures];
  for (const gId of groups) {
    const members = updated.filter((f) => f.groupId === gId);
    const n = members.length;
    members.forEach((f, idx) => {
      f.orderInGroup = idx;
      f.stageX = n <= 1 ? 0 : -1 + (2 * idx) / (n - 1);
      f.stageY = rowYByGroup[gId];
    });
  }
  return updated;
}

